/**
 * Business suite schema (Sales, Customers, Policies, Staff, Money, Settings).
 *
 * Conventions
 *  - Everything lives in the `business` schema.
 *  - Every table: `id uuid` primary key, `created_at`, `updated_at` (kept current by a trigger), `created_by`
 *    (the signed-in staff user, nullable for seeded rows).
 *  - Relationships are real foreign keys. Lookups are restricted (ON DELETE RESTRICT) so a branch, product or
 *    staff member that is in use cannot be deleted by accident; child rows of a parent record cascade.
 *  - Allowed values are CHECK constraints (easy to extend in a later migration, unlike Postgres enums).
 *  - Money is numeric(14,2); percentages numeric(5,2).
 *
 * The statements are idempotent, so the same list is used by the TypeORM migration (production) and by the
 * API on start-up in development.
 */
const T = (name: string, body: string) => `CREATE TABLE IF NOT EXISTS business.${name} (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
${body},
  created_by uuid REFERENCES identity.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
)`;
const oneOf = (col: string, values: string[]) => `CHECK (${col} IN (${values.map((v) => `'${v.replace(/'/g, "''")}'`).join(', ')}))`;
const money = (col: string, extra = 'NOT NULL DEFAULT 0') => `  ${col} numeric(14,2) ${extra} CHECK (${col} >= 0)`;
const fk = (col: string, table: string, opts = 'ON DELETE RESTRICT', nullable = true) =>
  `  ${col} uuid ${nullable ? '' : 'NOT NULL '}REFERENCES business.${table}(id) ${opts}`;

